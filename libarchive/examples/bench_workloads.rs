//! The three workloads the app actually does, timed the same way on a workstation and on a phone.
//!
//! Run it on the host:
//!
//! ```text
//! CARGO_TARGET_DIR=/home/user/cargo-target-libarchive \
//!   cargo run --release --offline --example bench_workloads -- \
//!   /home/user/bench-corpus/big.zip /home/user/bench-corpus/solid400big.7z
//! ```
//!
//! A third argument selects one workload, which is what you want under a profiler: profiling all
//! three together reports the sum, and the sum is dominated by whichever is slowest.
//!
//! ```text
//! bench_workloads <big.zip> <solid.7z> write     # only the writer, so perf attributes cleanly
//! ```
//!
//! Run the identical binary on a device (see `tools/run-on-device.sh`):
//!
//! ```text
//! bench_workloads /sdcard/big.zip /sdcard/solid400big.7z
//! ```
//!
//! # What this measures, and what it deliberately does not
//!
//! The workloads are the three a file manager spends its time on, in the order a user meets them:
//!
//! 1. **list** — open an archive and walk its entry list. This is what happens when a user taps
//!    a folder. It is the one that has to be fast on a 700 MB archive, because it gates
//!    everything after it.
//! 2. **extract 7z** — read every entry out of a solid 7Z, in order, through the public `Read`.
//!    Solid blocks are the case where holding the archive open is worth real time, and this is
//!    the only workload that can show whether it still is.
//! 3. **write zip** — write 5,000 small entries. What happens when a user selects a folder and
//!    taps compress.
//!
//! Each reports a **minimum of N runs**, not a mean. The reason is that every number this
//! program prints is meant to be compared against another number from another machine, and a
//! mean on a loaded machine is a statement about the machine. The minimum is the closest thing
//! to "what this costs when nothing else is happening", which is the thing being compared.
//!
//! ## Why there is no assertion in here
//!
//! This is a measurement, not a test. A wall-clock assertion in a program that is expected to
//! run on a phone, a workstation and an emulator would fail on two of those three for reasons
//! that have nothing to do with the code. The properties that *are* worth asserting live in
//! `tests/`, where they can be stated as ratios and bounds rather than as milliseconds.
//!
//! ## Why it prints the build, the corpus and the machine
//!
//! A number without the conditions it was taken under is not reproducible. Every run prints the
//! git revision, the target triple, the corpus file sizes and entry counts, and the load
//! average, so a result pasted into a message can be told apart from a result that was
//! remembered. If the corpus was generated by this repository rather than by `zip` or `7z`, the
//! run says so, because a fixture its own author produced does not measure anything.

use std::fs::File;
use std::io::{Cursor, Write};
use std::io::Read;
use std::time::{Duration, Instant};

use libarchive::{
    detect, ArchiveReader, ArchiveWriter, Format, NewEntry, OpenOptions, WriteOptions,
};

/// How many times each workload runs. The minimum is reported.
const RUNS: usize = 5;
/// How many extra repetitions a single-workload run does, so `perf` has enough samples to
/// attribute rather than reporting three of them.
const PROFILE_RUNS: usize = 40;

fn main() {
    let arguments: Vec<String> = std::env::args().skip(1).collect();
    if arguments.len() < 2 {
        eprintln!("usage: bench_workloads <big.zip> <solid.7z> [list|extract|write|all]");
        eprintln!("see the module documentation for what each number means");
        std::process::exit(2);
    }

    banner();
    let (zip, seven) = (&arguments[0], &arguments[1]);
    // Default is everything; a single word narrows it. An unknown word is an error rather than a
    // silent full run, because a profile of the wrong workload that looks like a profile of the
    // right one is worse than no profile.
    let selected = arguments.get(2).map(String::as_str).unwrap_or("all");
    let wanted = |name: &str| matches!(selected, "all" | "any") || selected == name;
    if !matches!(selected, "all" | "any" | "list" | "extract" | "write") {
        eprintln!("unknown workload {selected:?}; expected list, extract, write or all");
        std::process::exit(2);
    }
    println!("  workload     {selected}");
    // One workload selected means the caller wants a profile or a focused number rather than a
    // summary, and five runs of a 200 ms workload is not enough sample for `perf` to attribute.
    let runs = if matches!(selected, "all" | "any") { RUNS } else { PROFILE_RUNS };
    println!("  runs         {runs} for this workload");
    println!();

    if wanted("list") {
        println!("--- 1. list: open and walk the entry list ---------------------------------");
        match listing(zip, runs) {
            Ok(line) => println!("{line}"),
            Err(error) => println!("SKIPPED: {error}"),
        }
        println!();
    }

    if wanted("extract") {
        println!("--- 2. extract: every entry of a solid 7Z, in order ----------------------");
        match extracting(seven, runs) {
            Ok(line) => println!("{line}"),
            Err(error) => println!("SKIPPED: {error}"),
        }
        println!();
    }

    if wanted("write") {
        println!("--- 3. write: 5,000 small entries -----------------------------------------");
        match writing(runs) {
            Ok(line) => println!("{line}"),
            Err(error) => println!("SKIPPED: {error}"),
        }
        println!();
    }

    println!("Compare like with like: the same binary, the same corpus, on both machines.");
}

/// Everything needed to tell whether a number from this run can be compared with another.
fn banner() {
    println!("libarchive workloads");
    println!("  revision    {}", revision());
    println!("  target      {}", std::env::consts::ARCH);
    println!("  reports     minimum of the runs named below");
    println!("  loadavg     {}", load_average());
    println!();
}

fn revision() -> String {
    // Read the revision out of the environment rather than shelling out: there is no `git` on a
    // phone, and a number that cannot say what it was taken on is exactly the number this
    // project has had trouble with before.
    // Read at run time first, because that is what `tools/run-on-device.sh` can pass through
    // `adb shell`, and fall back to the compile-time value for a plain `cargo run`.
    std::env::var("LIBARCHIVE_REVISION")
        .ok()
        .or_else(|| option_env!("LIBARCHIVE_REVISION").map(str::to_string))
        .unwrap_or_else(|| "unknown (set LIBARCHIVE_REVISION)".to_string())
}

/// Milliseconds, as a plain number, so it lines up in a column with everything else.
fn ms(duration: Duration) -> f64 {
    duration.as_secs_f64() * 1000.0
}

fn load_average() -> String {
    match std::fs::read_to_string("/proc/loadavg") {
        Ok(text) => text.split_whitespace().take(3).collect::<Vec<_>>().join(" "),
        // Android has no /proc/loadavg in the same shape, and saying so is better than
        // printing a plausible-looking zero.
        Err(_) => "unavailable on this platform".to_string(),
    }
}

/// Open an archive and walk its entry list, touching no entry data.
///
/// The entry list is what the UI renders, so this is the time from tapping a folder to seeing
/// it. Bytes-read is reported as well as time, because a listing that is fast because it read
/// the whole archive into a buffer is fast in the wrong way, and only the byte count shows it.
fn listing(path: &str, runs: usize) -> Result<String, String> {
    let bytes = std::fs::metadata(path).map_err(|error| format!("{path}: {error}"))?.len();

    let (mut best, mut names, mut detected) = (Duration::MAX, 0usize, String::new());
    let mut listed = 0usize;
    for _ in 0..runs {
        let mut file = File::open(path).map_err(|error| format!("{path}: {error}"))?;
        if detected.is_empty() {
            detected = format!("{:?}", detect(&mut file).map_err(|error| error.to_string())?);
        }
        let start = Instant::now();
        let reader = ArchiveReader::open(file, &OpenOptions::default())
            .map_err(|error| error.to_string())?;
        let walk: usize = reader.entries().iter().map(|entry| entry.name.len()).sum();
        let elapsed = start.elapsed();
        names = reader.len();
        listed = walk;
        best = best.min(elapsed);
    }

    Ok(format!(
                "{:<22} {:>10.2} ms   {names} entries, {listed} B of names, detect={detected}, archive={bytes} B",
        "list",
        ms(best),
    ))
}

/// Read every entry of a solid 7Z in archive order, through the public `Read`.
///
/// Entries are read in 128 KiB blocks, which is what the app's extraction does, so this
/// includes the per-read cost the app pays rather than measuring the codec alone.
fn extracting(path: &str, runs: usize) -> Result<String, String> {
    let bytes = std::fs::metadata(path).map_err(|error| format!("{path}: {error}"))?.len();

    let (mut best, mut count, mut produced) = (Duration::MAX, 0usize, 0u64);
    for _ in 0..runs {
        let file = File::open(path).map_err(|error| format!("{path}: {error}"))?;
        let start = Instant::now();
        let mut reader =
            ArchiveReader::open(file, &OpenOptions::default()).map_err(|error| error.to_string())?;
        let mut buffer = vec![0u8; 128 * 1024];
        let mut got = 0u64;
        let mut read = 0usize;
        for index in 0..reader.len() {
            let mut entry = reader.open_entry(index).map_err(|error| error.to_string())?;
            loop {
                let n = entry.read(&mut buffer).map_err(|error| error.to_string())?;
                if n == 0 {
                    break;
                }
                got += n as u64;
            }
            read += 1;
        }
        let elapsed = start.elapsed();
        best = best.min(elapsed);
        count = read;
        produced = got;
    }

    let throughput = if best.as_secs_f64() > 0.0 {
        produced as f64 / best.as_secs_f64() / (1024.0 * 1024.0)
    } else {
        0.0
    };
    Ok(format!(
        "{:<22} {:>10.2} ms   {count} entries, {produced} B out, {throughput:.1} MiB/s, archive={bytes} B",
        "extract",
        ms(best),
    ))
}

/// Write 5,000 small entries into a sink that counts nothing.
///
/// The sink is a `Vec` rather than a file on purpose: a file's page cache would absorb the
/// write cost and this number would then be about the filesystem. What is left is the writer
/// and the codec, which is what is being compared between machines.
fn writing(runs: usize) -> Result<String, String> {
    let mut best = Duration::MAX;
    let mut size = 0usize;
    for _ in 0..runs {
        let sink = Cursor::new(Vec::with_capacity(4 * 1024 * 1024));
        let start = Instant::now();
        let written = write_archive(sink).map_err(|error| error.to_string())?;
        best = best.min(start.elapsed());
        size = written;
    }
    Ok(format!(
        "{:<22} {:>10.2} ms   5,000 entries x 512 B, deflate, sink is memory -> {size} B",
        "write",
        ms(best),
    ))
}

fn write_archive(sink: Cursor<Vec<u8>>) -> Result<usize, libarchive::Error> {
    let mut writer = ArchiveWriter::create(sink, Format::Zip, &WriteOptions::default())?;
    for index in 0..5_000u32 {
        let payload: Vec<u8> = (0..512usize)
            .map(|o| ((index as usize * 31 + o) % 251) as u8)
            .collect();
        writer.write_entry_from_slice(
            &NewEntry::file(format!("entry_{index:05}.bin")).with_size(payload.len() as u64),
            &payload,
        )?;
    }
    let sink = writer.finish_into()?;
    Ok(sink.into_inner().len())
}