//! The differential sweep: every corpus archive that more than one reader supports is read by
//! each of them, and they must agree on entry names, sizes and contents.
//!
//! The three other readers are unarc-rs 0.7.2 (the crate this one replaces for the long tail),
//! sevenz-rust2 0.23.0 (the 7Z implementation this crate wraps) and oxiarc-archive at 93b17af
//! (the fork the app itself shipped). Agreement is checked, never assumed: an archive this crate
//! writes and reads back only proves its writer and its reader agree with each other.
//!
//! Which readers are expected to handle which archive is the manifest's `oracles` list
//! (`tests/corpus/manifest.json`); the corpus itself is generated by
//! `python3 libarchive/tests/corpus/generate.py`, which also fixes the entry ground truth from
//! the *plaintext* the archives were made from. A record with `status: "pending"` names an
//! owner and a known gap: disagreements on those archives are counted and printed, not failed.
//! Everything else is a failure — two readers that both answer must give the same answer, and a
//! reader the manifest names must answer at all.
//!
//! Run the sweep with:
//!
//! ```text
//! cargo test --offline --test differential -- --nocapture
//! ```
//!
//! Its last line prints how many archives, oracle pairs and entry answers it compared. A run
//! without the corpus fails immediately with "compared 0 archives" and the command that
//! regenerates it, so an empty run can never look like a full one.

mod support;

use libarchive::entry::EntryKind;
use libarchive::{ArchiveReader, Format, Limits, OpenOptions};
use support::*;

/// What one sweep compared, so the final line reports counts and not adjectives.
#[derive(Default)]
struct Counts {
    /// Archives where at least one comparison was actually made (against an oracle or the
    /// manifest's ground truth).
    archives: usize,
    /// (archive, oracle) pairs where both sides produced an entry list.
    oracle_pairs: usize,
    /// Entry answers compared: once per entry per oracle pair, plus once per manifest entry
    /// checked against our own reader.
    entry_answers: usize,
}

impl Counts {
    fn report(&self) -> String {
        format!(
            "compared {} archives, {} oracle pairs, {} entry answers",
            self.archives, self.oracle_pairs, self.entry_answers
        )
    }
}

/// The result of one manifest record: disagreements, known gaps, and whether ours failed in the
/// way the record says it should.
struct RecordOutcome {
    failures: Vec<String>,
    gaps: Vec<String>,
    compared: bool,
}

/// Sweeps one manifest record.
fn sweep_record(record: &ManifestFile, counts: &mut Counts) -> RecordOutcome {
    let label = record.path.clone();
    let mut failures = Vec::new();
    let mut gaps = Vec::new();
    let mut compared = false;
    let pending = record.status == "pending";
    let path = corpus_root().join(&record.path);
    if !path.exists() {
        failures.push(format!("{label}: missing from the corpus"));
        return RecordOutcome {
            failures,
            gaps,
            compared,
        };
    }

    let ours = read_ours(
        &path,
        &record.format,
        record.password.as_deref(),
        Limits::default(),
    );

    // The record's `expect` is the first contract: some archives must open and read, some must
    // produce an honest Err. Getting this backwards is how a regression hides behind a passing
    // differential. An archive that must fail is not swept further when it does fail — except
    // that ours failing where an oracle succeeds is exactly the pending gap the sweep exists to
    // print, so the oracle loop below runs either way.
    match (&ours, record.expect.kind.as_str()) {
        (Err(_), "error") => {
            if let Some(kind) = &record.expect.error_kind {
                let message = ours.as_ref().unwrap_err();
                if !error_kind_named(message, parse_error_kind(kind)) {
                    failures.push(format!("{label}: expected Err({kind}), got: {message}"));
                }
            }
        }
        (Err(message), "ok") => {
            failures.push(format!(
                "{label}: the manifest says this archive opens and reads, but we got: {message}"
            ));
            return RecordOutcome {
                failures,
                gaps,
                compared,
            };
        }
        (Err(message), other) => {
            failures.push(format!(
                "{label}: manifest expect.kind {other:?} is not ok|error (we got: {message})"
            ));
            return RecordOutcome {
                failures,
                gaps,
                compared,
            };
        }
        (Ok(_), "error") => {
            let count = ours.as_ref().map(|entries| entries.len()).unwrap_or(0);
            failures.push(format!(
                "{label}: the manifest says opening this archive must fail, but we listed \
                 {count} entries"
            ));
            return RecordOutcome {
                failures,
                gaps,
                compared,
            };
        }
        (Ok(_), "ok") => {}
        (Ok(_), other) => {
            failures.push(format!(
                "{label}: manifest expect.kind {other:?} is not ok|error"
            ));
            return RecordOutcome {
                failures,
                gaps,
                compared,
            };
        }
    }

    if let (Ok(ours), Some(expected)) = (&ours, &record.entries) {
        let checked = compare_against_manifest(ours, expected, &label);
        compared = true;
        counts.entry_answers += expected.len();
        for message in checked {
            if pending {
                gaps.push(message);
            } else {
                failures.push(message);
            }
        }
    }

    if record.oracles.is_empty() {
        return RecordOutcome {
            failures,
            gaps,
            compared,
        };
    }
    for (oracle, theirs) in run_oracles(&path, record) {
        match (&ours, theirs) {
            (Ok(ours), Ok(theirs)) => {
                let message_label = format!("{label} [ours vs {oracle}]");
                let checked = compare_against_oracle(
                    ours,
                    &theirs,
                    &message_label,
                    stored_crc_is_content_crc(&record.format),
                );
                compared = true;
                counts.oracle_pairs += 1;
                counts.entry_answers += ours.len();
                for message in checked {
                    if pending {
                        gaps.push(message);
                    } else {
                        failures.push(message);
                    }
                }
            }
            (Ok(_), Err(message)) => {
                // The manifest names this oracle as a reader for this archive, so its failure is
                // a broken contract on the manifest's side — never a pending gap.
                failures.push(format!(
                    "{label}: the manifest names {oracle} as a reader for this archive, \
                     but it failed: {message}"
                ));
            }
            (Err(ours_message), Ok(theirs)) => {
                let gap = format!(
                    "{label}: we cannot read this archive ({ours_message}), but {oracle} \
                     lists {} entries",
                    theirs.len()
                );
                if pending {
                    gaps.push(gap);
                } else {
                    failures.push(gap);
                }
            }
            (Err(ours_message), Err(theirs_message)) => {
                let gap = format!(
                    "{label}: we failed ({ours_message}) and the manifest's oracle {oracle} \
                     failed too ({theirs_message})"
                );
                if pending {
                    gaps.push(gap);
                } else {
                    failures.push(gap);
                }
            }
        }
    }
    RecordOutcome {
        failures,
        gaps,
        compared,
    }
}

/// The sweep itself. The count it prints is the difference between a run with a corpus and a
/// run without one; the assert keeps the sweep from passing by comparing nothing.
#[test]
fn every_multi_reader_archive_agrees() {
    if !corpus_root().join("manifest.json").exists() {
        panic!(
            "the corpus is absent: compared 0 archives, 0 oracle pairs, 0 entry answers. \
             Regenerate it with: python3 libarchive/tests/corpus/generate.py"
        );
    }
    let manifest = load_manifest();
    let mut counts = Counts::default();
    let mut failures = Vec::new();
    let mut gaps = Vec::new();
    for record in &manifest.files {
        eprintln!("sweep: {}", record.path);
        let outcome = sweep_record(record, &mut counts);
        if outcome.compared {
            counts.archives += 1;
        }
        failures.extend(outcome.failures);
        gaps.extend(outcome.gaps);
    }
    for gap in &gaps {
        println!("known gap (status=pending, owner in the manifest): {gap}");
    }
    println!("differential: {}", counts.report());
    assert!(
        counts.archives > 0,
        "the sweep compared nothing ({}) — the manifest lists no archive with a readable \
         entry list, which means the corpus or the manifest is empty",
        counts.report()
    );
    if !failures.is_empty() {
        panic!(
            "{} disagreements between readers:\n{}",
            failures.len(),
            failures.join("\n")
        );
    }
}

/// `zip/symlink.zip` has no generic oracle comparison — symlink semantics differ per reader —
/// so its contract lives here: `link.txt` is a symlink whose target is `hello.txt`.
///
/// This fails today for a real reason: our ZIP reader reports the symlink entry as a regular
/// file (`formats/zip.rs` sets `EntryKind::File` and `symlink_target: None` for every entry and
/// never looks at the Unix mode bits where `zip -y` stored the link). Ignored, not deleted, so
/// the gap stays visible; the fix is to read the mode and the link target, and then to drop the
/// `#[ignore]`.
#[test]
#[ignore = "our ZIP reader reports symlink entries as File; owner: team zip"]
fn symlink_zip_lists_a_symlink_to_hello() {
    let path = corpus_root().join("generated/zip/symlink.zip");
    let file = std::fs::File::open(&path).expect("the symlink corpus file");
    let mut reader = ArchiveReader::open_as(file, Format::Zip, &OpenOptions::default())
        .expect("the symlink ZIP opens");
    let link = (0..reader.len())
        .filter_map(|index| reader.entry(index))
        .find(|entry| entry.name == "link.txt")
        .expect("link.txt is listed");
    assert_eq!(link.kind, EntryKind::Symlink, "link.txt must be a symlink");
    assert_eq!(link.symlink_target.as_deref(), Some("hello.txt"));
}

/// An encrypted ZIP without the password must fail with `Password`, not with wrong bytes.
#[test]
fn zipcrypto_without_the_password_is_a_password_error() {
    let path = corpus_root().join("generated/zip/zipcrypto.zip");
    let result = read_ours(&path, "zip", None, Limits::default());
    let message = result.expect_err("an encrypted ZIP without a password must not open");
    assert!(
        message.contains("Password"),
        "expected Err(Password), got: {message}"
    );
}
