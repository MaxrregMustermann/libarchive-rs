//! The solid-7Z bar, measured rather than believed.
//!
//! This is not a criterion benchmark. It is an assertion, because the property at stake is not
//! "fast" but "not quadratic": reading *n* entries of a solid block must not cost *n* decodes.
//! A criterion number would let that regress to something still faster than the old code while
//! being wrong, which is exactly the failure this project already shipped once.
//!
//! What is measured, on the vendored crate's own `solid.7z`:
//!
//! | | time |
//! |---|---|
//! | `sevenz-rust2::read_file`, one call per entry | the thing being replaced |
//! | `ArchiveReader::open_entry`, in order | the thing being shipped |
//!
//! and then the same entries against `non_solid.7z`, which is the same data stored without a
//! shared block, so the two decode the same bytes with different amounts of wasted work.
//!
//! Run it with `cargo test --release --test sevenz_solid -- --nocapture --ignored`, because
//! building a solid archive and reading it 400 times takes long enough that it should not be part
//! of the default test run.

use std::time::Instant;

use libarchive::error::Error as LibError;
use libarchive::{ArchiveReader, OpenOptions};

/// The vendored crate's corpus. Present because it is upstream's own test corpus, which is the
/// most real 7Z data available without downloading anything.
fn resource(name: &str) -> std::path::PathBuf {
    std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../vendor/sevenz-rust2/tests/resources")
        .join(name)
}

/// A 400-entry solid archive, and the same 400 entries stored one block each.
///
/// Generated by `7z` itself rather than by this project, because an archive that only the code
/// under test can produce proves nothing about the code under test. `LIBARCHIVE_BENCH_CORPUS`
/// points at the directory holding them; see `tools/make-corpus.sh`.
///
/// The pair is the whole experiment: identical bytes, identical codec, one shared block against
/// four hundred. Any difference in time between them is the cost of the shared block, and any
/// *growth* in that difference with the entry count is the quadratic signature.
fn corpus(name: &str) -> Option<std::path::PathBuf> {
    let dir = std::env::var_os("LIBARCHIVE_BENCH_CORPUS")?;
    let path = std::path::PathBuf::from(dir).join(name);
    path.is_file().then_some(path)
}

/// Reads every entry of `path` in order and returns how many bytes came out.
fn read_all_in_order(path: &std::path::Path) -> Result<(u64, u64), Box<dyn std::error::Error>> {
    let file = std::fs::File::open(path)?;
    let mut reader = ArchiveReader::open(file, &OpenOptions::default())?;
    let mut total = 0u64;
    for index in 0..reader.len() {
        let mut entry = reader.open_entry(index)?;
        let read = std::io::copy(&mut entry, &mut std::io::sink())?;
        total += read;
    }
    Ok((reader.len() as u64, total))
}

#[test]
#[ignore = "times two archives; run with --ignored --nocapture"]
fn solid_is_not_quadratic() {
    let (solid, non_solid) = match (corpus("solid400big.7z"), corpus("nonsolid400big.7z")) {
        (Some(solid), Some(non_solid)) => (solid, non_solid),
        _ => {
            eprintln!(
                "skipping: set LIBARCHIVE_BENCH_CORPUS to a directory holding \
                       solid400big.7z and nonsolid400big.7z (tools/make-corpus.sh makes them)"
            );
            return;
        }
    };

    let start = Instant::now();
    let (entries, bytes) = read_all_in_order(&solid).expect("reads solid.7z");
    let solid_time = start.elapsed();

    let start = Instant::now();
    let (control_entries, control_bytes) =
        read_all_in_order(&non_solid).expect("reads non_solid.7z");
    let non_solid_time = start.elapsed();

    println!("solid.7z      {entries} entries, {bytes} bytes in {solid_time:?}");
    println!(
        "non_solid.7z  {control_entries} entries, {control_bytes} bytes in {non_solid_time:?}"
    );
    println!(
        "ratio {:.1}x",
        solid_time.as_secs_f64() / non_solid_time.as_secs_f64().max(1e-9)
    );

    // The property, stated as a bound rather than as a comparison: a solid block costs one extra
    // decode of the same bytes, so it may be slower, but it may not be slower by the number of
    // entries. Four times the entries must not cost anywhere near four times the time.
    let ratio = solid_time.as_secs_f64() / non_solid_time.as_secs_f64().max(1e-9);
    assert!(
        ratio < 4.0,
        "reading a solid archive took {ratio:.1}x the non-solid equivalent, which is the \
         quadratic signature"
    );
}

#[test]
#[ignore = "times the crate being replaced; run with --ignored --nocapture"]
fn the_crate_being_replaced_is_the_slow_one() {
    // This is the comparison that justifies the vendored patch. If it ever stops being true, the
    // patch has stopped earning its maintenance cost and should be reconsidered rather than
    // carried forward forever.
    let Some(solid) = corpus("solid400big.7z") else {
        eprintln!("skipping: set LIBARCHIVE_BENCH_CORPUS to a directory holding solid400big.7z");
        return;
    };

    let start = Instant::now();
    let mut read_file_total = 0u64;
    {
        use sevenz_rust2::{ArchiveReader as SevenZReader, Password};
        let file = std::fs::File::open(&solid).expect("opens");
        let mut archive = SevenZReader::new(file, Password::empty()).expect("parses");
        // `archive()` is the only accessor for the entry list, and `read_file` takes a *name*
        // and rebuilds a decode stack per call. That is the cost this project exists to remove,
        // so it is called exactly the way the app used to call it: once per entry, by name.
        let names: Vec<String> = archive
            .archive()
            .files
            .iter()
            .filter(|file| file.has_stream)
            .map(|file| file.name.clone())
            .collect();
        for name in &names {
            let bytes = archive.read_file(name).expect("reads");
            read_file_total += bytes.len() as u64;
        }
    }
    let read_file_time = start.elapsed();

    let start = Instant::now();
    let (_, cursor_total) = read_all_in_order(&solid).expect("reads");
    let cursor_time = start.elapsed();

    println!("read_file, one call per entry: {read_file_time:?} ({read_file_total} bytes)");
    println!("open_entry, in order:          {cursor_time:?} ({cursor_total} bytes)");
    assert_eq!(
        read_file_total, cursor_total,
        "the two paths returned different bytes, so the timings are not comparable"
    );

    assert!(
        cursor_time < read_file_time,
        "the cursor ({cursor_time:?}) was not faster than read_file ({read_file_time:?})"
    );
    println!(
        "speedup {:.1}x",
        read_file_time.as_secs_f64() / cursor_time.as_secs_f64().max(1e-9)
    );
}

/// The same assertion, over BCJ2.
///
/// BCJ2 is the one folder shape that is decoded as a graph rather than a chain: four input streams,
/// one branched coder. It was refused outright until the graph walk was added to the vendored
/// `BlockCursor`, so this test is the measurement that the walk earns its cost on the shape it
/// exists for. Without the walk there is nothing to time, which is the point.
#[test]
#[ignore = "times two archives; run with --ignored --nocapture"]
fn bcj2_is_not_quadratic_either() {
    let (solid, non_solid) = match (
        corpus("bcj2solid400big.7z"),
        corpus("bcj2nonsolid400big.7z"),
    ) {
        (Some(solid), Some(non_solid)) => (solid, non_solid),
        _ => {
            eprintln!(
                "skipping: set LIBARCHIVE_BENCH_CORPUS to a directory holding bcj2solid400big.7z \
                 and bcj2nonsolid400big.7z (tools/make-corpus.sh makes them)"
            );
            return;
        }
    };

    // That the fixture really is the branched shape, rather than an ordinary chain whose name
    // mentions BCJ2. A test that measured a chain here would prove nothing about the graph walk.
    let solid_listing = std::process::Command::new("7z")
        .arg("l")
        .arg("-slt")
        .arg(&solid)
        .output()
        .expect("7z lists the solid fixture");
    assert!(
        String::from_utf8_lossy(&solid_listing.stdout).contains("Method = LZMA2:384k BCJ2"),
        "the solid BCJ2 fixture is not a BCJ2 archive, so the ratio below measures nothing"
    );

    let start = Instant::now();
    let (entries, bytes) = read_all_in_order(&solid).expect("reads the solid BCJ2 archive");
    let solid_time = start.elapsed();

    let start = Instant::now();
    let (control_entries, control_bytes) =
        read_all_in_order(&non_solid).expect("reads the non-solid BCJ2 archive");
    let non_solid_time = start.elapsed();

    assert_eq!(
        entries, control_entries,
        "the two archives hold different entries"
    );
    assert_eq!(
        bytes, control_bytes,
        "the two archives hold different bytes"
    );

    println!("bcj2solid400big.7z   {entries} entries, {bytes} bytes in {solid_time:?}");
    println!(
        "bcj2nonsolid400big.7z {control_entries} entries, {control_bytes} bytes in {non_solid_time:?}"
    );
    println!(
        "ratio {:.1}x",
        solid_time.as_secs_f64() / non_solid_time.as_secs_f64().max(1e-9)
    );

    let ratio = solid_time.as_secs_f64() / non_solid_time.as_secs_f64().max(1e-9);
    assert!(
        ratio < 4.0,
        "reading a solid BCJ2 archive took {ratio:.1}x the non-solid equivalent, which is the \
         quadratic signature: one decode per entry instead of one per folder"
    );

    // And against the way the app reads it today: one `read_file` per entry, which rebuilds the
    // whole coder graph for each. For BCJ2 that graph is four decoders and four pack streams, so
    // rebuilding it 400 times is expensive in a way a linear chain is not.
    let start = Instant::now();
    let mut read_file_total = 0u64;
    {
        use sevenz_rust2::{ArchiveReader as SevenZReader, Password};
        let file = std::fs::File::open(&solid).expect("opens");
        let mut archive = SevenZReader::new(file, Password::empty()).expect("parses");
        let names: Vec<String> = archive
            .archive()
            .files
            .iter()
            .filter(|file| file.has_stream())
            .map(|file| file.name().to_owned())
            .collect();
        assert!(
            !names.is_empty(),
            "the BCJ2 fixture holds no streamed entries"
        );
        for name in &names {
            let bytes = archive.read_file(name).expect("reads");
            read_file_total += bytes.len() as u64;
        }
    }
    let read_file_time = start.elapsed();

    assert_eq!(
        read_file_total, bytes,
        "read_file returned different bytes, so the two timings are not comparable"
    );
    println!("bcj2 read_file, one call per entry: {read_file_time:?}");
    assert!(
        solid_time < read_file_time,
        "one graph walk took {solid_time:?} where read_file took {read_file_time:?}"
    );
    println!(
        "bcj2 speedup {:.1}x",
        read_file_time.as_secs_f64() / solid_time.as_secs_f64().max(1e-9)
    );
}
